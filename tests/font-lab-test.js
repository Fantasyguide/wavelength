'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const puppeteer=require('puppeteer-core');

(async()=>{
  const artifact=path.resolve(process.argv[2]||'Wavelength-Font-Lab.html');
  assert(fs.existsSync(artifact),'build the standalone HTML before this test');
  const downloads=fs.mkdtempSync(path.join(os.tmpdir(),'wl-font-lab-'));
  const browser=await puppeteer.launch({executablePath:require('./chrome.js')(),headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
  try{
    const page=await browser.newPage();
    const errors=[],external=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url());});
    await page.setViewport({width:1600,height:1200,deviceScaleFactor:1});
    const cdp=await page.createCDPSession();await cdp.send('Page.setDownloadBehavior',{behavior:'allow',downloadPath:downloads});
    await page.goto(pathToFileURL(artifact).href,{waitUntil:'load'});
    await page.waitForFunction(()=>document.querySelector('#preview').contentDocument?.querySelector('#nameA')?.textContent==='幻想乡');
    const frame=page.frames().find(f=>f!==page.mainFrame());
    await frame.evaluate(()=>document.fonts.ready);
    await page.waitForFunction(()=>!document.querySelector('#layout-status').textContent.includes('正在准备'));
    assert.deepEqual(await frame.evaluate(()=>[innerWidth,innerHeight]),[3904,672]);
    const initial=await frame.$eval('#nameA',e=>({family:getComputedStyle(e).fontFamily,size:parseFloat(getComputedStyle(e).fontSize)}));
    assert(initial.family.includes('Wavelength PingXian')&&initial.size===116);
    assert.equal(await frame.$eval('#scoreA',el=>parseFloat(getComputedStyle(el).fontSize)),208);
    assert.equal(await frame.$eval('.phase-message',el=>el.textContent),'第 3 轮 · 结算');
    assert.equal(await frame.$eval('#timer-display',el=>el.parentElement.id),'display-footer');
    assert.equal(await frame.$eval('#directionB',el=>getComputedStyle(el).backgroundColor),'rgb(211, 211, 211)');
    assert.equal(await frame.$$('.team-dial').then(els=>els.length),0);
    assert.deepEqual(await frame.$$eval('.band-label',els=>els.map(el=>el.textContent)),['2','3','4','3','2']);
    assert(await frame.$$eval('.audience-avatar img',els=>els.length===5&&els.every(img=>img.src.startsWith('data:image/svg+xml'))));
    assert.equal(await page.$eval('#layout-status',el=>el.classList.contains('warning')),false,'default layout fits');
    await input('font-stroke','0.012');
    assert(Math.abs(await frame.$eval('#nameA',e=>parseFloat(getComputedStyle(e).webkitTextStrokeWidth))-1.392)<.01,'micro stroke can be edited independently of font weight');
    await page.click('#reset-group');
    const clickPoint=await page.evaluate(()=>{const frame=document.querySelector('#preview'),outer=frame.getBoundingClientRect(),inner=frame.contentDocument.querySelector('.side .con .l').getBoundingClientRect(),scale=outer.width/3904;return{x:outer.left+(inner.left+inner.width/2)*scale,y:outer.top+(inner.top+inner.height/2)*scale};});
    await page.mouse.click(clickPoint.x,clickPoint.y);
    assert.equal(await page.$eval('#selected-name',e=>e.textContent),'大题目 / 概念','clicking the game selects its typography group');
    async function input(id,value,event='input'){
      await page.$eval('#'+id,(el,{value,event})=>{el.value=value;el.dispatchEvent(new Event(event,{bubbles:true}));},{value,event});
    }
    await input('font-size','84');
    assert.equal(await frame.$eval('.side .con',e=>parseFloat(getComputedStyle(e).fontSize)),84);
    await page.click('#remember-a');await input('font-size','96');
    await page.click('#compare-a');assert.equal(await frame.$eval('.side .con',e=>parseFloat(getComputedStyle(e).fontSize)),84);
    await page.click('#compare-a');assert.equal(await frame.$eval('.side .con',e=>parseFloat(getComputedStyle(e).fontSize)),96);
    await page.$eval('[data-palette=a]',el=>{el.value='#007799';el.dispatchEvent(new Event('input',{bubbles:true}));});
    assert.equal(await frame.$eval('#nameA',el=>getComputedStyle(el).color),'rgb(0, 119, 153)');
    await page.click('#follow-color');await input('group-color','#334455');
    assert(await frame.$$eval('.side .con .l,.side .con .r',els=>els.every(el=>getComputedStyle(el).color==='rgb(51, 68, 85)')),'concept color edits reach both colored words');
    await page.click('#follow-color');
    await page.$eval('[data-palette=arrow]',el=>{el.value='#bfbfbf';el.dispatchEvent(new Event('input',{bubbles:true}));});
    assert.equal(await frame.$eval('#directionB',el=>getComputedStyle(el).backgroundColor),'rgb(191, 191, 191)');
    await input('font-name','DejaVu Sans','change');
    await page.waitForFunction(()=>document.querySelector('#font-status').textContent.includes('DejaVu Sans'));
    assert(await frame.$eval('.side .con',el=>getComputedStyle(el).fontFamily.includes('DejaVu Sans')));
    await page.select('#stage','chooseCard');assert.equal(await frame.$$('.card-choice').then(v=>v.length),2);
    await page.select('#stage','over');assert.equal(await frame.$eval('.phase-message',el=>el.textContent),'第 3 轮 · 复盘');
    await page.select('#zoom','1');assert.equal(await page.$eval('#canvas-holder',el=>el.clientWidth),3904);
    await page.select('#zoom','fit');
    await page.$eval('#long-text',el=>el.click());
    assert.equal(await frame.$eval('#nameA',el=>el.textContent),'超长名称幻想乡队');
    await page.$eval('#normal-text',el=>el.click());
    // Font file imports and saving HTML must survive reopening in another context.
    await page.click('[data-group=concepts]');
    await page.$('#font-files').then(el=>el.uploadFile(path.resolve(__dirname,'../assets/fantasyguide/ZaoZiGongFangYanSongTi-1.otf')));
    await page.waitForFunction(()=>document.querySelector('#font-status').textContent.includes('文件 ·'));
    const family=await frame.$eval('.side .con',el=>getComputedStyle(el).fontFamily);
    assert(family.includes('Lab File '));
    await page.click('#export-json');
    async function downloaded(name){await page.waitForFunction(()=>true);for(let i=0;i<100;i++){const file=path.join(downloads,name);if(fs.existsSync(file))return file;await new Promise(r=>setTimeout(r,50));}throw new Error('Missing download: '+name);}
    const jsonPath=await downloaded('Wavelength-字体方案.json');
    const config=JSON.parse(fs.readFileSync(jsonPath,'utf8'));
    assert.equal(config.groups.concepts.size,96);assert.equal(config.palette.a,'#007799');assert(config.fontFiles.length===1);
    assert.equal(config.palette.arrow,'#bfbfbf');assert.equal(config.baseline,'straight-arrows-16');
    await page.click('#save-html');
    const savedPath=await downloaded('Wavelength-字体试验台.html');
    assert(fs.statSync(savedPath).size<fs.statSync(artifact).size+3_000_000,'saved HTML does not duplicate iframe/font payloads');
    const isolated=await browser.createBrowserContext();const reopened=await isolated.newPage();
    reopened.on('pageerror',e=>errors.push(e.message));reopened.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url());});
    await reopened.goto(pathToFileURL(savedPath).href,{waitUntil:'load'});
    await reopened.waitForFunction(()=>document.querySelector('#preview').contentDocument?.querySelector('.side .con'));
    const restored=reopened.frames().find(f=>f!==reopened.mainFrame());
    await restored.evaluate(()=>document.fonts.ready);
    assert.equal(await restored.$eval('.side .con',el=>getComputedStyle(el).fontFamily),family);
    assert.equal(await restored.$eval('.side .con',el=>parseFloat(getComputedStyle(el).fontSize)),96);
    assert.equal(await restored.$eval('#nameA',el=>getComputedStyle(el).color),'rgb(0, 119, 153)');
    assert(await restored.evaluate(()=>Array.from(document.fonts).some(f=>f.family.startsWith('Lab File ')&&f.status==='loaded')),'imported font is embedded and loads after reopen');
    await isolated.close();
    await page.click('#reset-all');
    await page.$('#json-file').then(el=>el.uploadFile(jsonPath));
    await page.waitForFunction(()=>document.querySelector('#font-size').value==='96');
    assert.equal(await frame.$eval('.side .con',el=>parseFloat(getComputedStyle(el).fontSize)),96,'JSON restores edits');
    await page.$('#json-file').then(el=>el.uploadFile(path.resolve(__dirname,'../design/font-lab/applied-scheme.json')));
    await page.waitForFunction(()=>document.querySelector('#font-size').value==='86');
    assert(await frame.$eval('#nameA',el=>getComputedStyle(el).fontFamily.includes('Wavelength PingXian')),'previous user scheme maps to its embedded font');
    // Denied enumeration must retain the fallback tools; no false success message.
    await page.evaluate(()=>{window.queryLocalFonts=async()=>{throw new DOMException('denied','NotAllowedError');};});
    await page.click('#scan-fonts');
    assert(await page.$eval('#font-status',el=>el.textContent.includes('仍可输入字体名')));
    await page.evaluate(()=>{window.queryLocalFonts=async()=>[{family:'Local Sample Serif',style:'Regular',postscriptName:'SampleSerif',fullName:'Local Sample Serif'}];});
    await page.click('#scan-fonts');assert(await page.$eval('#font-list',el=>[...el.options].some(o=>o.value==='Local Sample Serif')));
    await page.click('[data-group=numbers]');await input('font-name','Wavelength Song','change');
    assert(await page.$eval('#font-status',el=>el.textContent.includes('数字区域请选')));
    await page.click('#reset-all');await page.select('#stage','revealed');
    await page.click('[data-group=names]');
    await page.setViewport({width:1400,height:1200,deviceScaleFactor:1});
    await frame.evaluate(()=>document.fonts.ready);
    const screenshot=process.env.WL_FONT_LAB_SCREENSHOT;if(screenshot)await page.screenshot({path:screenshot,fullPage:true});
    assert.deepEqual(errors,[]);assert.deepEqual(external,[],'offline lab makes no HTTP requests');
    console.log('FONT LAB PASSED: offline file, native viewport, click-to-edit, type/color, A/B, local-file font, saved HTML reopen, JSON round trip, font API fallback, numeral protection.');
  }finally{await browser.close();fs.rmSync(downloads,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exit(1);});
