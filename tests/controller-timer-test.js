"use strict";
const assert = require("node:assert/strict");
const WL = require("../game");
const ControllerTimer = require("../controller-timer");
let now = 1000;
const state = WL.createGame();
const timer = new ControllerTimer(state, { now: () => now, monotonicNow: () => now });
function create(kind, durationMs, owner = "controller-a") {
  Object.assign(state, { timerKind: kind, timerEnd: now + durationMs, timerDurationMs: durationMs, timerSerial: state.timerSerial + 1 });
  timer.sync(owner);
  return state.timerSync.id;
}
for (const [kind, duration] of [["chooseCard", 10000], ["dial", 60000], ["guess", 15000]]) {
  const id = create(kind, duration);
  now += 4000;
  assert.equal(state.timerEnd, null, "delivery does not consume the visible duration");
  assert.equal(timer.report({ type: "started", timerId: id, elapsedMs: 0 }, "controller-b"), false);
  assert(timer.report({ type: "started", timerId: id, elapsedMs: 0 }, "controller-a"));
  assert.equal(state.timerEnd, now + duration);
  const deadline = state.timerEnd;
  now += 1000;
  assert.equal(timer.report({ type: "started", timerId: id, elapsedMs: 0 }, "controller-a"), false);
  assert.equal(state.timerEnd, deadline, "repeat acknowledgements cannot extend a timer");
  state.timerEnd = now - 5000;
  assert.equal(timer.due(), false, "the server deadline cannot race a live controller");
  assert.equal(timer.report({ type: "expired", timerId: id, elapsedMs: duration }, "controller-a"), false);
  assert(timer.report({ type: "expired", timerId: id, elapsedMs: duration + 1500 }, "controller-a"));
  assert(state.timerEnd + 1500 <= now);
  assert(timer.due(), "only the owner's expiry ends its clock");
}
const progress = create("dial", 60000);
assert(timer.report({ type: "started", timerId: progress, elapsedMs: 0 }, "controller-a"));
now += 1000;
assert(timer.report({ type: "progress", timerId: progress, elapsedMs: 1100 }, "controller-a"));
assert.equal(state.timerSync.elapsedMs, 1100, "followers receive the actual owner clock");
const progressEnd = state.timerEnd;
assert.equal(timer.report({ type: "progress", timerId: progress, elapsedMs: 500 }, "controller-a"), false);
assert.equal(state.timerEnd, progressEnd, "out-of-order progress cannot rewind a countdown");
assert.equal(timer.report({ type: "progress", timerId: progress, elapsedMs: 1200 }, "controller-b"), false);
now += 5999;
assert.equal(timer.fallback(), false);
now++;
assert(timer.fallback(), "six seconds without owner progress activates the fallback");
assert.equal(state.timerSync.source, "server");
assert.equal(timer.report({ type: "progress", timerId: progress, elapsedMs: 1300 }, "controller-a"), false,
  "a late packet cannot reclaim a fallback and rewind time");
assert.equal(state.timerEnd, progressEnd);
const old = create("chooseCard", 10000);
const redraw = create("chooseCard", 10000, "controller-b");
assert.notEqual(old, redraw);
assert.equal(timer.report({ type: "expired", timerId: old, elapsedMs: 11500 }, "controller-a"), false);
assert.equal(state.timerEnd, null);
assert(timer.report({ type: "started", timerId: redraw, elapsedMs: 2000 }, "controller-b"));
assert.equal(state.timerEnd, now + 8000, "ack retry accounts for time already displayed");
create("guess", 15000);
now += 29999;
assert.equal(timer.fallback(), false);
now++;
assert(timer.fallback());
assert.equal(state.timerEnd, now + 15000, "missing controller gets a bounded server fallback");
const fallback = state.timerEnd;
timer.fallback();
assert.equal(state.timerEnd, fallback);
create("guess", 7000, null);
assert.equal(state.timerEnd, now + 7000, "headless clients retain server timing");
state.timerKind = null;
timer.sync("controller-a");
assert.equal(state.timerSync, null);
console.log("CONTROLLER TIMER TEST PASSED: visible budgets, owner progress, expiry authority, stale reports, grace and fallback");
